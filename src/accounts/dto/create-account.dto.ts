import {
  IsBoolean,
  IsEmail,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
  Length,
  MaxLength,
} from 'class-validator';

export class CreateAccountDto {
  @IsUUID() companyId: string;
  @IsUUID() mainAccountId: string;
  @IsOptional() @IsUUID() parentAccountId?: string;
  @IsString() @IsNotEmpty() @Length(1, 150) accountName: string;
  @IsOptional() @IsString() @MaxLength(500) description?: string;
  @IsOptional() @IsEmail() @MaxLength(150) email?: string;
  @IsOptional() @IsBoolean() isHeader?: boolean;
  @IsOptional() @IsBoolean() isControlAccount?: boolean;
  @IsOptional() @IsBoolean() allowPosting?: boolean;

  // Rejected by the service: account codes are generated by the backend.
  @IsOptional() @IsString() accountCode?: string;
}
